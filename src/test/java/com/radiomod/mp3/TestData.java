package com.radiomod.mp3;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;

import org.junit.jupiter.api.Assumptions;

/**
 * Access to the data generated by {@code reference/prepare_testdata.py} (see {@code build.gradle.kts}).
 *
 * <p>If the data is missing the tests that need it fail, unless the build was run with
 * {@code -PskipTestData}: then they are skipped.
 */
final class TestData {
    private static volatile Manifest manifest;

    private TestData() {
    }

    /** One file of the manifest: a corpus file or an ISO vector. */
    record Entry(String kind, String name, Path mp3, Path ref, Path nopcmRef, Map<String, String> attrs) {
        boolean isVector() {
            return kind.equals("vector");
        }

        String attr(String key) {
            return attrs.getOrDefault(key, "");
        }

        byte[] bytes() {
            return read(mp3);
        }

        @Override
        public String toString() {
            return name;
        }
    }

    record Manifest(Path dir, Map<String, String> header, List<Entry> entries) {
    }

    static Path dir() {
        String d = System.getProperty("minimp3.testdata");
        return d == null ? Path.of("build", "testdata") : Path.of(d);
    }

    /** The manifest, or a skipped/failed test if the data has not been generated. */
    static Manifest manifest() {
        Manifest m = manifest;
        if (m == null) {
            synchronized (TestData.class) {
                if (manifest == null) {
                    manifest = load();
                }
                m = manifest;
            }
        }
        if (m.entries.isEmpty()) {
            String message = "no test data in " + dir().toAbsolutePath()
                    + ": run 'gradlew prepareTestData' (or the tests without -PskipTestData)";
            if (Boolean.getBoolean("minimp3.testdata.optional")) {
                Assumptions.abort(message);
            }
            throw new AssertionError(message);
        }
        return m;
    }

    private static Manifest load() {
        Path dir = dir();
        Path file = dir.resolve("manifest.tsv");
        Map<String, String> header = new LinkedHashMap<>();
        List<Entry> entries = new ArrayList<>();
        if (Files.isRegularFile(file)) {
            for (String line : readLines(file)) {
                String[] f = line.split("\t", -1);
                if (line.startsWith("#")) {
                    if (f.length == 2) {
                        header.put(f[0].substring(1), f[1]);
                    }
                    continue;
                }
                Map<String, String> attrs = new LinkedHashMap<>();
                for (String kv : f[5].split(";")) {
                    int eq = kv.indexOf('=');
                    if (eq > 0) {
                        attrs.put(kv.substring(0, eq), kv.substring(eq + 1));
                    }
                }
                entries.add(new Entry(f[0], f[1], dir.resolve(f[2]), f[3].isEmpty() ? null : dir.resolve(f[3]),
                        f[4].isEmpty() ? null : dir.resolve(f[4]), Collections.unmodifiableMap(attrs)));
            }
        }
        return new Manifest(dir, Collections.unmodifiableMap(header), List.copyOf(entries));
    }

    static List<Entry> entries() {
        return manifest().entries();
    }

    static Stream<Entry> withReference() {
        return entries().stream().filter(e -> e.ref() != null);
    }

    static Stream<Entry> corpus(String group) {
        return entries().stream().filter(e -> !e.isVector() && e.attr("group").equals(group));
    }

    static Stream<Entry> vectors() {
        return entries().stream().filter(Entry::isVector);
    }

    static Entry entry(String name) {
        return entries().stream().filter(e -> e.name().equals(name)).findFirst()
                .orElseThrow(() -> new AssertionError("no test file " + name));
    }

    /** The minimp3 checkout the reference was built from. */
    static Path minimp3() {
        return Path.of(manifest().header().get("minimp3"));
    }

    static byte[] read(Path p) {
        try {
            return Files.readAllBytes(p);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    static List<String> readLines(Path p) {
        try {
            return Files.readAllLines(p, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** Writes a report to build/reports/minimp3, with the JDK in the file name. */
    static void report(String name, String text) {
        String dir = System.getProperty("minimp3.reports");
        if (dir == null) {
            return;
        }
        String suffix = System.getProperty("minimp3.report.suffix", "");
        try {
            Path d = Path.of(dir);
            Files.createDirectories(d);
            Files.writeString(d.resolve(name + suffix + ".md"), text, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
